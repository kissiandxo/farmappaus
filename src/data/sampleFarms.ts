const R = (open: string, close: string): TimeRange => [open, close];

const on = (keys: DayKey[], range: TimeRange): Partial<Record<DayKey, TimeRange[]>> =>
  Object.fromEntries(keys.map((k) => [k, [range]]));

const MON_SAT: DayKey[] = ['mon', 'tue', 'wed', 'thu', 'fri', 'sat'];
const EVERY_DAY: DayKey[] = ['sun', 'mon', 'tue', 'wed', 'thu', 'fri', 'sat'];

const weekly = (days: Partial<Record<DayKey, TimeRange[]>>, note?: string): OpeningHours => ({
  kind: 'weekly',
  days,
  note,
});

const prod = (
  category: ProductCategory,
  name: string,
  priceCents: number,
  unit: string,
  extra: Partial<Product> = {},
): Product => ({ category, name, priceCents, unit, inStock: true, ...extra });

const lic = (
  category: LicenceCategory,
  regulator: string,
  n: string,
  status: Licence['status'] = 'self_declared',
): Licence => ({
  category,
  regulator,
  licenceNumber: `SAMPLE-${n}`,
  expiresOn: '2030-12-31',
  status,
});

